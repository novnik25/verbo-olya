/**
 * Шкала темпа речи — ОДНА на всё приложение.
 *
 * Раньше её было две: панель предлагала −25/0/25/50/75, а раздел настроек —
 * −20/0/20/40. Значения одной шкалы во второй не существовали, и выпадающий
 * список в настройках, не найдя сохранённого значения, молча показывал первый
 * вариант: темп 1,25× отображался как «Замедленный». Стоило тронуть этот
 * список — и темп перезаписывался тем, что было показано.
 *
 * Значение хранится в процентах прибавки к обычному темпу: 25 → «+25%» в
 * разметке речи, что даёт ровно 1,25× (проверено замером длительности звука).
 */
export const SPEED_STEPS: Array<{ value: number; label: string }> = [
  { value: -25, label: '0,75×' },
  { value: 0, label: '1×' },
  { value: 25, label: '1,25×' },
  { value: 50, label: '1,5×' },
  { value: 75, label: '1,75×' }
]

/** Подпись шага по его значению. */
export function rateLabel(value: number): string {
  return SPEED_STEPS.find((s) => s.value === value)?.label ?? ''
}

/**
 * Приводит сохранённый темп к ближайшему шагу шкалы. Нужен для значений,
 * сохранённых прежними версиями (−20, 20, 40), и вообще для любого мусора:
 * значение вне шкалы делает регулятор нечитаемым и опасным.
 * При точной середине между шагами берём МЕНЬШИЙ — ускорять без спроса нельзя.
 */
export function snapRate(value: number): number {
  if (typeof value !== 'number' || !Number.isFinite(value)) return 0
  let лучший = SPEED_STEPS[0].value
  let ближе = Math.abs(value - лучший)
  for (const s of SPEED_STEPS) {
    const d = Math.abs(value - s.value)
    if (d < ближе) {
      ближе = d
      лучший = s.value
    }
  }
  return лучший
}
