/**
 * Фирменный знак Verbo: «V» из двух штрихов с точкой над вершиной — она же
 * читается как галочка речевой волны.
 *
 * Знак был нарисован ТРИЖДЫ, каждый раз в своей системе координат: логотип в
 * окне (кубик 0..24), иконка приложения (0..256) и оформление установщика
 * (собственные формулы со scale). Пропорции успели разойтись: штрих
 * относительно ширины отличался на четверть, точка стояла на разной высоте.
 *
 * Канон теперь один — этот. Масштабировать его нигде не нужно: SVG умеет
 * вкладываться со своей системой координат, поэтому и логотип, и установщик
 * просто вставляют кубик 0..256 нужного размера. Формул масштабирования, а
 * значит и мест для расхождения, не осталось.
 */
export const MARK = {
  /** Сторона кубика, в котором нарисован знак. */
  box: 256,
  strokeWidth: 26,
  /** Левый штрих — акцентом. */
  left: { x: 74, y: 84 },
  /** Общая вершина «V». */
  apex: { x: 128, y: 178 },
  /** Правый штрих — цветом текста. */
  right: { x: 182, y: 84 },
  /** Точка над вершиной. */
  dot: { x: 128, y: 62, r: 13 },
  /** Скругление подложки иконки. */
  radius: 58
} as const

/** Два штриха «V» готовыми значениями атрибута d. */
export function markPaths(): { accent: string; ink: string } {
  return {
    accent: `M${MARK.left.x} ${MARK.left.y} L${MARK.apex.x} ${MARK.apex.y}`,
    ink: `M${MARK.right.x} ${MARK.right.y} L${MARK.apex.x} ${MARK.apex.y}`
  }
}
