/**
 * Миграция стилей пользователя под новые версии встроенных промптов.
 * Возвращает обновлённый массив или null, если менять нечего.
 */
export function migrateStyles(current: Style[]): Style[] | null {
  let changed = false
  const migrated = current.map((st) => {
    if (!st.builtin) return st
    const builtin = BUILTIN_STYLES.find((b) => b.id === st.id)
    if (!builtin || builtin.prompt === st.prompt) return st
    if ((LEGACY_BUILTIN_PROMPTS[st.id] ?? []).includes(st.prompt)) {
      changed = true
      return { ...st, prompt: builtin.prompt }
    }
    return st
  })
  for (const builtin of BUILTIN_STYLES) {
    if (!migrated.some((st) => st.id === builtin.id)) {
      migrated.push(builtin)
      changed = true
    }
  }
  return changed ? migrated : null
}

