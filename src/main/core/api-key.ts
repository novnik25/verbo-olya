/**
 * Разбор вставленного ключа доступа — чистая логика, без сети.
 *
 * Ключ почти всегда приходит вставкой из браузера или переписки, и вместе с ним
 * приходит мусор: неразрывные пробелы, знаки нулевой ширины, кавычки по краям,
 * приставка «Bearer». Такой ключ вообще нельзя положить в заголовок запроса:
 * запрос падал ещё до отправки, а человеку показывали «ключ не принят сервисом» —
 * он искал причину в ключе, хотя ключ был верный.
 */

/** Знаки нулевой ширины и метка порядка байтов — их не видно, но они ломают заголовок. */
const НЕВИДИМЫЕ = /[\u200B-\u200D\uFEFF\u2060]/g

/** Годится ли ключ на роль значения HTTP-заголовка: только видимая латиница. */
const ТОЛЬКО_ВИДИМЫЕ = /^[\x21-\x7e]+$/

export type KeyShape = 'ok' | 'empty' | 'foreign-chars'

/**
 * Убирает из вставленного ключа всё, что попало туда при копировании.
 * Сам ключ не меняет: режет только обрамление и невидимые знаки.
 */
export function cleanApiKey(raw: string): string {
  let key = (raw ?? '').replace(НЕВИДИМЫЕ, '').trim()
  // снимаем обрамление слой за слоем: копируют и «"Bearer gsk_…"», и
  // «Bearer "gsk_…"» — за один проход второй слой оставался бы на месте
  for (let i = 0; i < 3; i++) {
    const было = key
    // кавычки по краям остаются от копирования из кода или из переписки
    if (key.length > 1 && /^["'`«“]/.test(key) && /["'`»”]$/.test(key)) {
      key = key.slice(1, -1)
    }
    // «Bearer gsk_…» — так ключ выглядит в примерах запросов, оттуда и копируют
    key = key.replace(/^bearer\s+/i, '').trim()
    if (key === было) break
  }
  return key
}

/**
 * Что не так с ключом ДО обращения к сервису. Отличать «в ключе посторонние
 * знаки» от «сервис не принял ключ» важно: советы человеку разные — в первом
 * случае скопировать заново, во втором идти в консоль за новым ключом.
 */
export function inspectApiKey(raw: string): { key: string; shape: KeyShape } {
  const key = cleanApiKey(raw)
  if (!key) return { key, shape: 'empty' }
  return { key, shape: ТОЛЬКО_ВИДИМЫЕ.test(key) ? 'ok' : 'foreign-chars' }
}
