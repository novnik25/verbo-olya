import { describe, it, expect } from 'vitest'
import { stamp } from '../src/main/core/logger'

describe('отметка времени в журнале', () => {
  it('пишется по МЕСТНЫМ часам, а не по всемирным', () => {
    // раньше бралось toISOString() — и в журнале было UTC. При разборе проблемы
    // время не сходилось с часами пользователя, и это сбивало с толку
    const d = new Date(2026, 7, 16, 14, 5, 9, 123) // 16 августа, 14:05:09.123 по местным
    expect(stamp(d)).toBe('14:05:09.123')
  })

  it('часы, минуты и секунды дополняются нулями', () => {
    expect(stamp(new Date(2026, 0, 2, 3, 4, 5, 6))).toBe('03:04:05.006')
  })

  it('полночь не превращается в 24 часа', () => {
    expect(stamp(new Date(2026, 0, 2, 0, 0, 0, 0))).toBe('00:00:00.000')
  })
})
